from functools import cache

import torch
import torch.nn as nn
from transformers import AutoConfig, AutoModel, AutoTokenizer, PreTrainedModel

MODEL_ID = "desklib/ai-text-detector-v1.01"


class DesklibAIDetectionModel(PreTrainedModel):
    """Transformer + mean pooling + linear head; needed to load the checkpoint."""

    config_class = AutoConfig

    def __init__(self, config):
        super().__init__(config)
        self.model = AutoModel.from_config(config)
        self.classifier = nn.Linear(config.hidden_size, 1)
        self.post_init()

    def forward(self, input_ids, attention_mask):
        hidden = self.model(input_ids, attention_mask=attention_mask)[0]
        mask = attention_mask.unsqueeze(-1).float()
        pooled = (hidden * mask).sum(dim=1) / mask.sum(dim=1).clamp(min=1e-9)
        return self.classifier(pooled)


@cache
def _load():
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    tokenizer = AutoTokenizer.from_pretrained(MODEL_ID)
    model = DesklibAIDetectionModel.from_pretrained(MODEL_ID).to(device).eval()
    return tokenizer, model, device


def desklib_detect(text: str, max_len: int = 768) -> float:
    """Return the probability (0-1) that `text` is AI-generated."""
    tokenizer, model, device = _load()
    enc = tokenizer(text, truncation=True, max_length=max_len, return_tensors="pt").to(device)
    with torch.no_grad():
        logit = model(enc["input_ids"], enc["attention_mask"])
    return torch.sigmoid(logit).item()


if __name__ == "__main__":
    print(desklib_detect("AI detection refers to the process of identifying whether a given piece of content has been generated by artificial intelligence."))
    print(desklib_detect("It is estimated that a major part of the content in the internet will be generated by AI by 2025. That is why if is important to have accurate tools"))
